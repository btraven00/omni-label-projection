#!/usr/bin/env python3
"""viash2ob: build an ob plan repo from an OpenProblems task (Viash components).

    tools/viash2ob.py TASK_DIR --dataset NAME=URL [--include a,b] [--exclude a,b]

For every component under src/{data_processors,methods,control_methods,metrics}
this writes modules/<name>/{run.sh,viash/<name>}: the component built with
viash's native engine plus a wrapper that rewrites ob's argv into the
component's.  Then it writes omnibenchmark.yaml (one entrypoint per component)
and plan.yaml, with stages derived from the component contracts
(design 013 §3.3) and one software_environment per distinct image+setup.

argv rewrite:
    --output <id>=<path>        -> --<viash output arg> <path>
    --<id> <path>  (stage input) -> --<viash input arg> <path>, or dropped when
                                    this component does not declare it
    --output_dir, --name        -> dropped
    --<param> <value>           -> unchanged
"""

import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

STAGE_OF = {"process_dataset": "process", "method": "methods",
            "control_method": "methods", "metric": "metrics"}
BARE_OUTPUT = {"method": "prediction", "control_method": "prediction", "metric": "score"}
SRC_DIRS = ["data_processors", "methods", "control_methods", "metrics"]

WRAPPER = r"""#!/usr/bin/env bash
# Generated by viash2ob. Rewrites ob's argv into the Viash component's argv.
set -euo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
declare -A INPUTS=%(inputs)s
declare -A OUTPUTS=%(outputs)s
declare -A DROP=%(drop)s
args=()
while [ $# -gt 0 ]; do
  case "$1" in
    --output_dir|--name) shift 2 ;;
    --output)
      id=${2%%%%=*}; path=${2#*=}
      [ -n "${OUTPUTS[$id]+x}" ] || { echo "viash2ob: unmapped output id '$id'" >&2; exit 2; }
      args+=("--${OUTPUTS[$id]}" "$path"); shift 2 ;;
    --*)
      key=${1#--}
      if [ -n "${INPUTS[$key]+x}" ]; then args+=("--${INPUTS[$key]}" "$2")
      elif [ -n "${DROP[$key]+x}" ]; then :
      else args+=("$1" "$2"); fi
      shift 2 ;;
    *) echo "viash2ob: unexpected positional '$1'" >&2; exit 2 ;;
  esac
done
exec "$HERE/viash/%(name)s" "${args[@]}"
"""

LOADER = r"""#!/usr/bin/env bash
# Data stage: fetch a common dataset (OpenProblems publishes them on S3).
set -euo pipefail
while [ $# -gt 0 ]; do
  case "$1" in --output) out=${2#*=} ;; --url) url=$2 ;; esac; shift 2
done
python -c 'import sys, urllib.request; urllib.request.urlretrieve(sys.argv[1], sys.argv[2])' "$url" "$out"
"""


def bash_assoc(d):
    return "(" + " ".join(f"[{k}]={v}" for k, v in d.items()) + ")"


def viash(root, *argv, check=True):
    # viash 0.9.7 exits 1 on `config view` even when it prints the config.
    r = subprocess.run(["viash", *argv], cwd=root, capture_output=True, text=True)
    if check and r.returncode:
        sys.exit(f"viash {' '.join(argv)} failed:\n{r.stderr}")
    return r.stdout


def ob_id(arg, ctype):
    for prefix in ("input_", "output_"):
        if arg.startswith(prefix):
            return arg[len(prefix):]
    if arg == "output":
        return BARE_OUTPUT[ctype]
    if arg == "input":
        return "dataset"
    return arg


def param_default(arg):
    # Viash stores every default as a list. A `multiple` argument takes all of
    # them in one flag joined by multiple_sep; ob would read a YAML list as a
    # parameter grid instead, so collapse to a scalar either way.
    values = arg["default"]
    if arg.get("multiple"):
        return arg.get("multiple_sep", ";").join(map(str, values))
    return values[0]


def load_component(root, cfg_path):
    cfg = json.loads(viash(root, "config", "view", str(cfg_path), "--format", "json", check=False))
    ctype = cfg["info"]["type"]
    args = [x for g in cfg.get("argument_groups", []) for x in g["arguments"]]
    files = [x for x in args if x["type"] == "file"]
    docker = next(e for e in cfg["engines"] if e["type"] == "docker")
    return dict(
        name=cfg["name"], namespace=cfg["namespace"], type=ctype, stage=STAGE_OF[ctype],
        config=str(cfg_path),
        inputs={ob_id(x["name"][2:], ctype): x["name"][2:] for x in files if x["direction"] == "input"},
        outputs={ob_id(x["name"][2:], ctype): x["name"][2:] for x in files if x["direction"] == "output"},
        params={x["name"][2:]: param_default(x) for x in args
                if x["type"] != "file" and x.get("default") is not None},
        env_key=json.dumps([docker["image"], docker.get("setup")], sort_keys=True),
        image=docker["image"],
        preferred_normalization=cfg["info"].get("preferred_normalization"),
    )


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("task_dir")
    ap.add_argument("--dataset", required=True, help="NAME=URL of a common dataset h5ad")
    ap.add_argument("--include", default="", help="comma-separated component names")
    ap.add_argument("--exclude", default="", help="comma-separated component names")
    a = ap.parse_args()
    root = Path(a.task_dir).resolve()
    repo = Path.cwd()
    include = set(filter(None, a.include.split(",")))
    exclude = set(filter(None, a.exclude.split(",")))

    import yaml  # PyYAML ships with ob's env; only needed for _viash.yaml
    task = yaml.safe_load((root / "_viash.yaml").read_text())
    registry = f"ghcr.io/{task['organization']}/{task['name']}"

    comps = []
    for d in SRC_DIRS:
        for cfg in sorted((root / "src" / d).glob("*/config.vsh.yaml")):
            c = load_component(root, cfg.relative_to(root))
            if (include and c["name"] not in include) or c["name"] in exclude:
                continue
            comps.append(c)

    # stage contracts = union of the member components' ids
    stages = {}
    for c in comps:
        s = stages.setdefault(c["stage"], dict(inputs=[], outputs=[]))
        for k in c["inputs"]:
            if k not in s["inputs"]:
                s["inputs"].append(k)
        for k in c["outputs"]:
            if k not in s["outputs"]:
                s["outputs"].append(k)

    # environments: one per distinct image+setup, referenced by the first member's ghcr tag
    envs = {}
    for c in comps:
        e = envs.setdefault(c["env_key"], dict(
            id=f"env_{c['name']}",
            ref=f"docker://{registry}/{c['namespace']}/{c['name']}:build_main",
            members=[]))
        e["members"].append(c["name"])
        c["env"] = e["id"]

    entrypoints = {}
    for c in comps:
        out = repo / "modules" / c["name"]
        out.mkdir(parents=True, exist_ok=True)
        viash(root, "build", c["config"], "--runner", "executable",
              "-c", '.engines := [{"type": "native"}]', "-o", str(out / "viash"))
        drop = {k: 1 for k in stages[c["stage"]]["inputs"] if k not in c["inputs"]}
        (out / "run.sh").write_text(WRAPPER % dict(
            inputs=bash_assoc(c["inputs"]), outputs=bash_assoc(c["outputs"]),
            drop=bash_assoc(drop), name=c["name"]))
        (out / "run.sh").chmod(0o755)
        entrypoints[c["name"]] = f"modules/{c['name']}/run.sh"
        print(f"built {c['stage']}/{c['name']}  in={list(c['inputs'])} out={list(c['outputs'])} "
              f"drop={list(drop)} params={c['params']} env={c['env']}", file=sys.stderr)

    ds_name, ds_url = a.dataset.split("=", 1)
    loader = repo / "modules" / "dataset"
    loader.mkdir(parents=True, exist_ok=True)
    (loader / "run.sh").write_text(LOADER)
    (loader / "run.sh").chmod(0o755)
    entrypoints["dataset"] = "modules/dataset/run.sh"
    # the loader only needs python: reuse the data processor's image
    loader_env = next((c["env"] for c in comps if c["stage"] == "process"), comps[0]["env"])

    (repo / "omnibenchmark.yaml").write_text(yaml.safe_dump({"entrypoints": entrypoints}, sort_keys=True))

    plan_stages = [{
        "id": "data",
        "modules": [{"id": ds_name, "software_environment": loader_env,
                     "repository": {"url": ".", "commit": "HEAD", "entrypoint": "dataset"},
                     "parameters": [{"url": ds_url}]}],
        "outputs": [{"id": "dataset", "path": "{module.id}.dataset.h5ad"}],
    }]
    for sid in ("process", "methods", "metrics"):
        if sid not in stages:
            continue
        mods = []
        for c in comps:
            if c["stage"] != sid:
                continue
            m = {"id": c["name"], "software_environment": c["env"],
                 "repository": {"url": ".", "commit": "HEAD", "entrypoint": c["name"]}}
            if c["params"]:
                m["parameters"] = [c["params"]]
            mods.append(m)
        plan_stages.append({
            "id": sid, "inputs": stages[sid]["inputs"], "modules": mods,
            "outputs": [{"id": o, "path": f"{{module.id}}.{o}.h5ad"} for o in stages[sid]["outputs"]],
        })

    plan = {
        "id": task["name"],
        "description": f"{task.get('label', task['name'])}: OpenProblems components run as ob modules (viash2ob)",
        "version": "0.1",
        "benchmarker": "viash2ob",
        "api_version": "0.8.0",
        "software_backend": "apptainer",
        "software_environments": {
            e["id"]: {"description": f"{c_image(e, comps)} + setup, shared by {', '.join(e['members'])}",
                      "apptainer": e["ref"]}
            for e in envs.values()},
        "stages": plan_stages,
    }
    (repo / "plan.yaml").write_text(yaml.safe_dump(plan, sort_keys=False, width=100))
    print(f"wrote plan.yaml: {len(comps)} components, {len(envs)} environments, "
          f"stages {[s['id'] for s in plan_stages]}", file=sys.stderr)


def c_image(env, comps):
    return next(c["image"] for c in comps if c["name"] == env["members"][0])


if __name__ == "__main__":
    main()
